// Order request checks shared by the web API and (later) the mobile app.
// Money is always integer kobo, even in requests.

/** Nigerian mobile numbers: 0 + [7|8|9] + [0|1] + 8 digits, e.g. 08031234567. */
const NIGERIAN_MOBILE = /^0[789][01]\d{8}$/;

/**
 * Turns "+234 803 123 4567", "2348031234567" or "0803-123-4567" into "08031234567".
 * Returns null if it isn't a Nigerian mobile number.
 */
export function normaliseNigerianPhone(input: string): string | null {
  let digits = input.replace(/[\s()-]/g, "");
  if (digits.startsWith("+")) digits = digits.slice(1);
  if (!/^\d+$/.test(digits)) return null;
  if (digits.startsWith("234") && digits.length === 13) digits = `0${digits.slice(3)}`;
  return NIGERIAN_MOBILE.test(digits) ? digits : null;
}

export interface CreateOrderRequest {
  productId: string;
  /** Normalised to 0XXXXXXXXXX. */
  recipientPhone: string;
  /** Airtime only: how much airtime, in kobo (whole naira). Data plans have a fixed price. */
  faceValueKobo?: number;
  /** Random id generated by the app per "Buy" tap, so retries don't charge twice. */
  clientReference?: string;
  /** The customer's 4-digit transaction PIN. */
  pin: string;
}

export type ParseResult<T> = { ok: true; value: T } | { ok: false; errors: Record<string, string> };

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const CLIENT_REFERENCE = /^[A-Za-z0-9_-]{1,100}$/;

export function parseCreateOrderRequest(body: unknown): ParseResult<CreateOrderRequest> {
  if (typeof body !== "object" || body === null || Array.isArray(body)) {
    return { ok: false, errors: { body: "Send a JSON object" } };
  }
  const input = body as Record<string, unknown>;
  const errors: Record<string, string> = {};

  const productId = input.productId;
  if (typeof productId !== "string" || !UUID.test(productId)) {
    errors.productId = "Choose a product";
  }

  const phone =
    typeof input.recipientPhone === "string" ? normaliseNigerianPhone(input.recipientPhone) : null;
  if (!phone) errors.recipientPhone = "Enter a valid Nigerian phone number, e.g. 08031234567";

  const faceValueKobo = input.faceValueKobo;
  if (
    faceValueKobo !== undefined &&
    (typeof faceValueKobo !== "number" ||
      !Number.isSafeInteger(faceValueKobo) ||
      faceValueKobo <= 0)
  ) {
    errors.faceValueKobo = "Amount must be a positive whole number of kobo";
  }

  const clientReference = input.clientReference;
  if (
    clientReference !== undefined &&
    (typeof clientReference !== "string" || !CLIENT_REFERENCE.test(clientReference))
  ) {
    errors.clientReference = "clientReference must be 1-100 letters, digits, - or _";
  }

  const pin = input.pin;
  if (typeof pin !== "string" || !/^\d{4}$/.test(pin)) {
    errors.pin = "Enter your 4-digit transaction PIN";
  }

  if (Object.keys(errors).length > 0) return { ok: false, errors };
  return {
    ok: true,
    value: {
      productId: productId as string,
      recipientPhone: phone as string,
      ...(faceValueKobo !== undefined ? { faceValueKobo: faceValueKobo as number } : {}),
      ...(clientReference !== undefined ? { clientReference: clientReference as string } : {}),
      pin: pin as string,
    },
  };
}

/**
 * What the customer pays for airtime: the face value minus their discount. The discount is
 * rounded down, so we never give away a fraction of a kobo.
 * Display only: the server works out the real charge.
 */
export function airtimeCostKobo(faceValueKobo: number, discountBps: number): number {
  return faceValueKobo - Math.floor((faceValueKobo * discountBps) / 10_000);
}
